/**
 * Guided tour content — the spoken half of the tutorial.
 *
 * The audience is clinic staff moving off paper notebooks, not software users.
 * So every step answers "what do I do here and why", never "this is the header
 * component". Steps are written to be read aloud once and remembered.
 *
 * A step's `target` is a CSS selector on a `data-tour` attribute. Keeping the
 * hooks in markup out of the class names means restyling a screen cannot
 * silently break the tour. A missing target is not an error: the step still
 * shows, centred, because its words are useful even when the element it points
 * at is off-screen (the sidebar on a phone, an empty list with nothing to
 * highlight).
 *
 * Every screen in the sidebar has a tour. Half-covering the app was worse than
 * not covering it: staff learn that «؟» sometimes explains the screen and
 * sometimes throws them into a long document, so they stop pressing it. Detail
 * routes (a single patient, one implant card) deliberately have none — they are
 * opened from a list whose tour already explained what they contain — and there
 * «؟» opens «الدليل» (/help) instead.
 */

export interface TourStep {
  /** CSS selector to spotlight. Omit for a centred, full-screen step. */
  target?: string;
  title: string;
  body: string;
}

