/** Steps for a route, or null when the screen has no tour. */
export function tourFor(pathname: string): TourStep[] | null {
  return TOURS[pathname] ?? null;
}

/** localStorage key marking a route's tour as already seen. */
export function tourSeenKey(pathname: string): string {
  return `zuha.tour.v1${pathname}`;
}
